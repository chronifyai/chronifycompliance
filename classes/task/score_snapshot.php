namespace local_chronifycompliance\task;

use local_chronifycompliance\score\health_score;

/**
 * Weekly snapshot of the health score, for the trend on the dashboard.
 *
 * @package    local_chronifycompliance
 * @copyright  2026 Sebale {@link https://sebale.net}
 * @license    http://www.gnu.org/copyleft/gpl.html GNU GPL v3 or later
 */
class score_snapshot extends \core\task\scheduled_task {
    /**
     * Task name.
     *
     * @return string
     */
    public function get_name(): string {
        return get_string('task:scoresnapshot', 'local_chronifycompliance');
    }

    /**
     * Store this week's score.
     */
    public function execute(): void {
        $score = health_score::snapshot();
        mtrace('Health score: ' . ($score->overall ?? 'none'));
    }
}
